const seed = async () => {
  await connectDB();

  console.log("Clearing existing data...");
  await Promise.all([
    Course.deleteMany({}),
    Platform.deleteMany({}),
    LearningPath.deleteMany({}),
  ]);

  console.log("Inserting platforms...");
  await Platform.insertMany(platforms);

  console.log("Inserting courses...");
  const insertedCourses = await Course.insertMany(courses);

  console.log("Inserting learning paths (linked to matching courses)...");
  const pathsWithCourses = learningPaths.map((path) => ({
    ...path,
    steps: path.steps.map((step) => ({
      ...step,
      recommendedCourseIds: insertedCourses
        .filter((c) => c.category.toLowerCase() === path.topic.toLowerCase())
        .slice(0, 3)
        .map((c) => c._id),
    })),
  }));
  await LearningPath.insertMany(pathsWithCourses);

  const adminEmail = "admin@coursefinder.dev";
  const existingAdmin = await User.findOne({ email: adminEmail });
  if (!existingAdmin) {
    console.log("Creating default admin user (admin@coursefinder.dev / admin1234)...");
    await User.create({
      name: "Admin",
      email: adminEmail,
      password: "admin1234",
      role: "admin",
    });
  }

  console.log("Seed complete.");
  await mongoose.connection.close();
  process.exit(0);
};

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
